// Saves today's real numbers for the concept video (the video is rendered from this file, offline)
//   node video/fetch-data.mjs   (with the server running on :8787)
import { writeFileSync, readFileSync } from 'node:fs';
const B = 'http://localhost:8787';
const j = async p => (await fetch(B + p)).json();
const map = await j('/api/live').catch(() => null);
const air = await j('/api/air');
const plan = await j('/api/outdoor');
const point = { lat: 43.2398, lng: 76.9455 }; // Abay Ave at Dostyk (rider pickup); driver waits near Mega Alma-Ata
const rider = await j(`/api/partner/brief?lang=en&role=rider&lat=${point.lat}&lng=${point.lng}`);
const driver = await j('/api/partner/brief?lang=en&role=driver&lat=43.2017&lng=76.8919');
const ask = JSON.parse(readFileSync(new URL('./ask.json', import.meta.url), 'utf8'));
const stations = (map?.stations || []).map(s => ({ lat: s.lat, lng: s.lng, pm25: s.pm25, c: s.category }));
writeFileSync(new URL('./data.json', import.meta.url), JSON.stringify({ at: air.at, city: air.city, districts: air.districts, plan: { best: plan.best, worst: plan.worst, hours: plan.hours },
  stations, rider: rider.rider, driver: driver.driver, send_push: rider.send_push,
  ask: { q: ask.question, a: ask.text.split(/(?<=\.)\s/)[0].replace(/\[\d+\]/g, ''), source: ask.sources[0]?.title, ms: ask.ms } }, null, 1));
console.log('stations', stations.length, 'city', air.city?.pm25, 'pickup', rider.rider?.pickup?.sensor, 'break', driver.driver?.break_spot?.sensor);

// The video is set at 7:45 a.m.: the best and worst two-hour windows over the whole day (06:00–22:00),
// from the same 24 hourly values, and the texts regenerated by the same code the API uses
const { roleMessage } = await import('../lib/partner.mjs');
const d = JSON.parse(readFileSync(new URL('./data.json', import.meta.url), 'utf8'));
const H = d.plan.hours.map(h => h.pm25);
const wins = []; for (let s = 6; s <= 20; s++) wins.push({ from: s, to: s + 2, pm25: Math.round((H[s] + H[s + 1]) / 2 * 10) / 10 });
const best = wins.reduce((a, b) => (b.pm25 < a.pm25 ? b : a)), worst = wins.reduce((a, b) => (b.pm25 > a.pm25 ? b : a));
d.plan.best = best; d.plan.worst = worst;
const pm25 = d.city.pm25;
const keep = (role, extra) => ({ ...roleMessage('en', role, { pm25, best, worst }), ...extra });
d.rider = keep('rider', { pickup: d.rider.pickup });
d.driver = keep('driver', { jam: d.driver.jam, break_spot: d.driver.break_spot });
writeFileSync(new URL('./data.json', import.meta.url), JSON.stringify(d, null, 1));
console.log('morning view: best', best, 'worst', worst);
